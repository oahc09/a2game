test('evidence-dir keeps exact input bytes with SHA before admission, on pass and fail, and fails closed on unusable paths',async()=>{
 const base=temp(),outputDirectory=join(base,'game');
 const fixture=await generateGame({prompt:'A deterministic three-click counter.',providerId:'fixture',outputDirectory});
 assert.equal(fixture.status,'PASS_REFERENCE');
 const file=join(outputDirectory,'game.json');
 const original=readFileSync(file,'utf8');
 writeFileSync(file,original.replace('{','{"id":"duplicate",'));
 const evidenceDir=join(base,'evidence');
 const failed=await testGeneratedDirectory(outputDirectory,{evidenceDir});
 assert.equal(failed.status,'FAIL');
 assert.equal(failed.evidence.files['game.json'].sha256.length,64);
 assert.deepEqual(readFileSync(join(failed.evidence.directory,'game.json'),'utf8'),readFileSync(file,'utf8'));
 const manifest=JSON.parse(readFileSync(join(failed.evidence.directory,'evidence-manifest.json'),'utf8'));
 assert.equal(manifest.format,'a2game-input-evidence');assert.equal(manifest.files['game.json'].sha256,failed.evidence.files['game.json'].sha256);
 writeFileSync(file,original);
 const ok=await validateGameFile(file,{evidenceDir});
 assert.equal(ok.status,'PASS_REFERENCE');assert.equal(ok.evidence.files['game.json'].bytes>0,true);
 assert.equal((await validateGameFile(file)).evidence,undefined);
 writeFileSync(join(base,'blocker'),'x');
 await assert.rejects(validateGameFile(file,{evidenceDir:join(base,'blocker')}),{code:'A2G_GEN_EVIDENCE'});
});
test('evidence binds original on-disk bytes for BOM and invalid UTF-8 inputs and captures game-plan.json',async()=>{
 const {createHash}=await import('node:crypto');
 const sha=b=>createHash('sha256').update(b).digest('hex');
 const base=temp(),outputDirectory=join(base,'game'),evidenceDir=join(base,'evidence');
 const fixture=await generateGame({prompt:'A deterministic three-click counter.',providerId:'fixture',outputDirectory});
 assert.equal(fixture.status,'PASS_REFERENCE');
 const original=readFileSync(join(outputDirectory,'game.json'));
 const bomFile=join(base,'bom.json');
 writeFileSync(bomFile,Buffer.concat([Buffer.from([0xEF,0xBB,0xBF]),original]));
 const bom=await validateGameFile(bomFile,{evidenceDir});
 assert.equal(bom.status,'PASS_REFERENCE');
 assert.equal(readFileSync(join(bom.evidence.directory,'game.json'))[0],0xEF);
 assert.equal(bom.evidence.files['game.json'].sha256,sha(readFileSync(bomFile)));
 const badFile=join(base,'bad.json');
 writeFileSync(badFile,Buffer.concat([Buffer.from([0xEF,0xBB,0xBF]),Buffer.from([0xFF,0xFE]),original]));
 await assert.rejects(validateGameFile(badFile,{evidenceDir}),error=>error.evidence&&error.evidence.files['game.json'].sha256===sha(readFileSync(badFile)));
 writeFileSync(join(outputDirectory,'game-plan.json'),'{"broken":');
 const failed=await testGeneratedDirectory(outputDirectory,{evidenceDir});
 assert.equal(failed.status,'FAIL');
 assert.equal(failed.evidence.files['game-plan.json'].sha256,sha(readFileSync(join(outputDirectory,'game-plan.json'))));
});
test('real CLI validate/test responses locate captured evidence for decode failures, BOM passes and plan binding',async()=>{
 const {createHash}=await import('node:crypto');
 const sha=b=>createHash('sha256').update(b).digest('hex');
 const base=temp(),evidenceDir=join(base,'evidence');
 // Invalid UTF-8: CLI fails (exit 2) and the FAIL JSON carries the evidence with exact raw bytes on disk.
 const badFile=join(base,'bad.json');
 const badBytes=Buffer.concat([Buffer.from([0xEF,0xBB,0xBF]),Buffer.from([0xFF,0xFE]),Buffer.from('game','utf8')]);
 writeFileSync(badFile,badBytes);
 const bad=runCli(['validate',badFile,'--evidence-dir',evidenceDir,'--json']);
 assert.equal(bad.status,2);
 const badJson=JSON.parse(bad.stdout);
 assert.equal(badJson.status,'FAIL');
 assert.equal(badJson.evidence.files['game.json'].sha256,sha(badBytes));
 assert.deepEqual(readFileSync(join(badJson.evidence.directory,'game.json')),badBytes);
 // BOM: CLI passes and evidence keeps the exact on-disk bytes.
 const fixture=await generateGame({prompt:'A deterministic three-click counter.',providerId:'fixture',outputDirectory:join(base,'game')});
 assert.equal(fixture.status,'PASS_REFERENCE');
 const bomFile=join(base,'bom.json');
 const bomBytes=Buffer.concat([Buffer.from([0xEF,0xBB,0xBF]),readFileSync(join(base,'game','game.json'))]);
 writeFileSync(bomFile,bomBytes);
 const bom=runCli(['validate',bomFile,'--evidence-dir',evidenceDir,'--json']);
 assert.equal(bom.status,0);
 const bomJson=JSON.parse(bom.stdout);
 assert.equal(bomJson.status,'PASS_REFERENCE');
 assert.equal(bomJson.evidence.files['game.json'].sha256,sha(bomBytes));
 assert.equal(readFileSync(join(bomJson.evidence.directory,'game.json'))[0],0xEF);
 // Optional game-plan.json read during test is captured with its exact bytes.
 writeFileSync(join(base,'game','game-plan.json'),'{"broken":');
 const plan=runCli(['test',join(base,'game'),'--evidence-dir',evidenceDir,'--json']);
 assert.equal(plan.status,1);
 const planJson=JSON.parse(plan.stdout);
 assert.equal(planJson.status,'FAIL');
 assert.equal(planJson.evidence.files['game-plan.json'].sha256,sha(readFileSync(join(base,'game','game-plan.json'))));
});
